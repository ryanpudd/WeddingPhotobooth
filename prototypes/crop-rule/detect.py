"""PROTOTYPE, throwaway. Branch prototype/crop-rule, never merged.

Runs RF-DETR Nano (people + COCO objects) and RTMPose-m (body keypoints) over the
test photos and writes raw detections to data.js for index.html. It also writes
960px-wide JPEG thumbnails to tmp/crop-rule-prototype/thumbs/ (gitignored), so no
photo is committed.

Usage (from the repo root, in a venv with onnxruntime, numpy, pillow, rtmlib):
    python prototypes/crop-rule/detect.py --rfdetr <path to rfdetr_nano model.onnx>
"""
import argparse, json, pathlib, time
import numpy as np
from PIL import Image
import onnxruntime as ort
from rtmlib import RTMPose

ROOT = pathlib.Path(__file__).resolve().parents[2]
SETS = {"booth": ROOT / "tmp/WeddingPhotobooth", "props": ROOT / "tmp/WeddingPhotosWithProps"}
THUMBS = ROOT / "tmp/crop-rule-prototype/thumbs"
POSE_URL = ("https://download.openmmlab.com/mmpose/v1/projects/rtmposev1/onnx_sdk/"
            "rtmpose-m_simcc-body7_pt-body7_420e-256x192-e48f03d0_20230504.zip")
LABELS = {1: "person", 27: "backpack", 28: "umbrella", 31: "handbag", 32: "tie", 34: "frisbee",
          37: "sports ball", 38: "kite", 39: "baseball bat", 43: "tennis racket", 44: "bottle",
          46: "wine glass", 47: "cup", 48: "fork", 49: "knife", 50: "spoon", 51: "bowl",
          52: "banana", 53: "apple", 61: "cake", 62: "chair", 63: "couch", 64: "potted plant",
          72: "tv", 73: "laptop", 75: "remote", 77: "cell phone", 84: "book", 85: "clock",
          86: "vase", 87: "scissors", 88: "teddy bear", 90: "toothbrush"}
MEAN = np.array([0.485, 0.456, 0.406], np.float32)
STD = np.array([0.229, 0.224, 0.225], np.float32)


def rfdetr(sess, img):
    w, h = img.size
    x = np.asarray(img.resize((384, 384), Image.BILINEAR), np.float32) / 255.0
    x = ((x - MEAN) / STD).transpose(2, 0, 1)[None]
    boxes, logits = sess.run(["pred_boxes", "logits"], {"pixel_values": x})
    prob = 1 / (1 + np.exp(-logits[0]))
    cls = prob.argmax(1)
    score = prob.max(1)
    out = []
    for b, c, s in zip(boxes[0], cls, score):
        if s < 0.25:
            continue
        cx, cy, bw, bh = b
        box = [float((cx - bw / 2) * w), float((cy - bh / 2) * h), float((cx + bw / 2) * w), float((cy + bh / 2) * h)]
        box = [max(0, box[0]), max(0, box[1]), min(w, box[2]), min(h, box[3])]
        out.append({"cls": LABELS.get(int(c), f"coco{int(c)}"), "score": round(float(s), 3),
                    "box": [round(v, 1) for v in box]})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rfdetr", required=True)
    a = ap.parse_args()
    sess = ort.InferenceSession(a.rfdetr, providers=["CPUExecutionProvider"])
    pose = RTMPose(onnx_model=POSE_URL, model_input_size=(192, 256), backend="onnxruntime", device="cpu")
    THUMBS.mkdir(parents=True, exist_ok=True)
    photos = []
    t0 = time.time()
    for set_name, folder in SETS.items():
        for p in sorted(folder.iterdir()):
            if p.suffix.lower() not in (".png", ".jpg", ".jpeg"):
                continue
            img = Image.open(p).convert("RGB")
            w, h = img.size
            dets = rfdetr(sess, img)
            persons = [d for d in dets if d["cls"] == "person"]
            objects = [d for d in dets if d["cls"] != "person"]
            if persons:
                bgr = np.asarray(img)[:, :, ::-1].copy()
                kps, kss = pose(bgr, bboxes=[d["box"] for d in persons])
                for d, kp, ks in zip(persons, kps, kss):
                    d["kpts"] = [[round(float(x), 1), round(float(y), 1), round(float(s), 2)]
                                 for (x, y), s in zip(kp, ks)]
            thumb = f"{set_name}-{p.stem}.jpg"
            img.resize((960, round(960 * h / w)), Image.LANCZOS).save(THUMBS / thumb, quality=85)
            photos.append({"name": p.name, "set": set_name, "w": w, "h": h, "thumb": thumb,
                           "persons": persons, "objects": objects})
            print(f"{set_name}/{p.name}: {len(persons)} people, {len(objects)} objects")
    print(f"{len(photos)} photos in {time.time() - t0:.0f}s")
    out = pathlib.Path(__file__).with_name("data.js")
    out.write_text("// PROTOTYPE data, generated by detect.py\nconst PHOTOS = " + json.dumps(photos) + ";\n")


if __name__ == "__main__":
    main()
